# The month block maps below are one example layout family (user-declared coordinates).
# They are not a universal appointment-book format; declare your own blocks for other grids.

from __future__ import annotations

from dataclasses import dataclass
from datetime import date


@dataclass(frozen=True)
class BloqueVertical:
    hoja: str
    fecha: date
    fila_encabezado: int
    fila_inicio: int
    fila_fin: int  # exclusiva


@dataclass(frozen=True)
class BloqueHorizontal:
    hoja: str
    fecha: date
    col_inicio: int  # columna de la hora
    col_fin: int  # exclusiva
    fila_encabezado: int
    fila_inicio: int
    fila_fin: int  # exclusiva


def _v(hoja: str, anio: int, mes: int, dia: int, enc: int, ini: int, fin: int) -> BloqueVertical:
    return BloqueVertical(hoja, date(anio, mes, dia), enc, ini, fin)


def _h(
    hoja: str, anio: int, mes: int, dia: int, c0: int, c1: int, enc: int, ini: int, fin: int
) -> BloqueHorizontal:
    return BloqueHorizontal(hoja, date(anio, mes, dia), c0, c1, enc, ini, fin)


